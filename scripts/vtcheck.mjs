const PORT = process.env.PORT || '8790';
﻿import fs from 'node:fs';
const CDP='http://127.0.0.1:9334';
const list=await (await fetch(`${CDP}/json/list`)).json();
const page=list.find(t=>t.type==='page'&&new RegExp(String(PORT)).test(t.url));
const ws=new WebSocket(page.webSocketDebuggerUrl);
await new Promise(r=>ws.onopen=r);
let id=0;const pending=new Map();const errs=[];
ws.onmessage=e=>{const m=JSON.parse(e.data);
 if(m.method==='Runtime.exceptionThrown') errs.push((m.params.exceptionDetails.exception?.description||'').split('\n')[0]);
 if(m.id&&pending.has(m.id)){pending.get(m.id)(m);pending.delete(m.id);}};
const send=(method,params={})=>new Promise(res=>{const i=++id;pending.set(i,res);ws.send(JSON.stringify({id:i,method,params}));});
const ev=async x=>(await send('Runtime.evaluate',{expression:x,awaitPromise:true,returnByValue:true})).result?.result?.value;
const shot=async f=>{const r=await send('Page.captureScreenshot',{format:'png'});fs.writeFileSync(f,Buffer.from(r.result.data,'base64'));};
await send('Runtime.enable');
await send('Network.setCacheDisabled',{cacheDisabled:true});
await send('Page.navigate',{url:`http://localhost:${PORT}/?v=`+Date.now()});
await new Promise(r=>setTimeout(r,2800));
console.log('vt support', await ev(`typeof document.startViewTransition`));
console.log('theme now', await ev(`document.documentElement.dataset.theme`));
// 点主题按钮，抓中途两帧
await ev(`document.querySelector('#btnTheme').click(); true`);
await new Promise(r=>setTimeout(r,150));
await shot('docs/preview-vt-1.png');
await new Promise(r=>setTimeout(r,140));
await shot('docs/preview-vt-2.png');
await new Promise(r=>setTimeout(r,600));
console.log('theme after', await ev(`document.documentElement.dataset.theme`), 'vt class', await ev(`document.documentElement.classList.contains('vt')`));
await shot('docs/preview-vt-3.png');
console.log(errs.slice(0,3).join('\n')||'no errors');
ws.close();
